/**
 * Полнота измерения показа в терминах кабинета.
 *
 * Показ режима vast_omid существует в двух видах. Если плеер площадки выдал
 * скрипту верификации полный доступ к странице и ветка коллекторов подключилась,
 * показ собирается штатным рантаймом и приходит на основную точку приёма со всеми
 * семью сигналами и композитным Score. Если доступ ограничен уровнем креатива или
 * ниже, прокрутки и окружения рекламы на странице не существует, S3 и S7 не
 * измеряются, а веса предполагают полный набор — композитный Score в таком показе
 * не рассчитывается.
 *
 * Поэтому дискриминатор здесь — наличие score_final, а не режим измерения:
 * ограничение chk_score_final_required допускает пустое значение исключительно
 * для vast_omid, так что обратное невозможно. Производить уровень из
 * measurement_mode было бы неверно: один и тот же режим даёт оба исхода.
 */

export type MeasurementLevel = 'full' | 'partial';

export interface MeasurementLevelSource {
    score_final: number | null;
}

export function resolveMeasurementLevel(row: MeasurementLevelSource): MeasurementLevel {
    return row.score_final === null ? 'partial' : 'full';
}

export const MEASUREMENT_LEVEL_LABELS: Record<MeasurementLevel, string> = {
    full: 'Полное',
    partial: 'Частичное',
};

